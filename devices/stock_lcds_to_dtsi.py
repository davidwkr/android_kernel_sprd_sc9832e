#!/usr/bin/env python3
# Extract the /lcds panel nodes of a stock (4.4, ADF binding) device tree into
# a .dtsi for the 4.14 ADF board variants.
#
# Input: the stock DTB decompiled with `dtc -I dtb -O dts` (get the DTB from
# the stock boot image's SPRD DT table, see the 4.4 tree's
# tools/sprd_bootimg.py). The stock panel nodes are already in the binding the
# 4.14 ADF port parses (drivers/video/adf/sprd/drv/sprd_panel.c); the only
# phandle in them is their own, and power sequences use raw GPIO numbers.
# This drops the phandle lines and gives every node a label PREFIX_<name>.
#
# Usage: python3 -I stock_lcds_to_dtsi.py STOCK.dts PREFIX OUT.dtsi
# Prints the panel-drivers line to paste into the board file.

import re
import sys


def main():
    if len(sys.argv) != 4:
        sys.exit('usage: stock_lcds_to_dtsi.py STOCK.dts PREFIX OUT.dtsi')
    src, prefix, out = sys.argv[1:]
    lines = open(src, encoding='ascii').read().split('\n')
    start = next(i for i, l in enumerate(lines) if l == '\tlcds {')
    depth, end = 0, None
    for i in range(start, len(lines)):
        depth += lines[i].count('{') - lines[i].count('}')
        if depth == 0:
            end = i
            break
    body = lines[start + 1:end]
    labels, res = [], []
    for l in body:
        if l.strip().startswith(('phandle = ', 'linux,phandle = ')):
            continue
        m = re.match(r'^\t\t(lcd[0-9a-fx]+)@([0-9a-fx]+) \{$', l)
        if m:
            label = '%s_%s' % (prefix, m.group(1))
            labels.append(label)
            l = '\t%s: %s@%s {' % (label, m.group(1), m.group(2))
        elif l.startswith('\t\t'):
            l = l[1:]
        res.append(l)
    with open(out, 'w') as f:
        f.write('// SPDX-License-Identifier: GPL-2.0\n'
                '/*\n'
                ' * Stock /lcds panel nodes, generated by devices/stock_lcds_to_dtsi.py\n'
                ' * from the stock DT; include inside a "lcds" node.\n'
                ' */\n\n')
        f.write('\n'.join(res).strip('\n') + '\n')
    print('panel-drivers = <%s>;' % ' '.join('&' + x for x in labels))


if __name__ == '__main__':
    main()
